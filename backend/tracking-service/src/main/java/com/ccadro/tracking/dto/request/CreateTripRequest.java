package com.ccadro.tracking.dto.request;

import jakarta.validation.constraints.NotNull;
import lombok.*;
import lombok.experimental.FieldDefaults;

import java.util.UUID;

@Data
@Builder
@NoArgsConstructor
@AllArgsConstructor
@FieldDefaults(level = AccessLevel.PRIVATE)
public class CreateTripRequest {
    @NotNull(message = "shipmentId must not be null")
    UUID shipmentId;

    @NotNull(message = "vehicleId must not be null")
    UUID vehicleId;

    @NotNull(message = "driverId must not be null")
    UUID driverId;

    UUID activeRouteVersionId;
    /** Deprecated compatibility field; trip codes are generated by Tracking Service. */
    String tripCode;
    String companyCode;
}

